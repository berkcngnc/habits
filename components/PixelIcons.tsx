export default function PixelIcon({ name, color, size = 24 }: PixelIconProps) {
  const grid = GRIDS[name] || GRIDS.Star;
  const rows = grid.length;
  const cols = grid[0].length;
  const pixelSize = size / cols;

  return (
    <View style={{ width: size, height: size }}>
      {grid.map((row, rIdx) => (
        <View key={rIdx} style={{ flexDirection: 'row', height: pixelSize }}>
          {row.map((val, cIdx) => (
            <View
              key={cIdx}
              style={{
                width: pixelSize,
                height: pixelSize,
                backgroundColor: val === 1 ? color : 'transparent',
              }}
            />
          ))}
        </View>
      ))}
    </View>
  );
}
